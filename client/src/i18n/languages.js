let currentLanguage = localStorage.getItem('vivaan_lang') || 'en';

export function getLanguage() {
  return currentLanguage;
}

export function setLanguage(langCode) {
  if (TRANSLATIONS[langCode]) {
    currentLanguage = langCode;
  } else {
    currentLanguage = 'en';
  }
  localStorage.setItem('vivaan_lang', currentLanguage);
  window.dispatchEvent(new CustomEvent('vivaan-language-changed', { detail: { lang: currentLanguage } }));
}

export function t(key) {
  const dict = TRANSLATIONS[currentLanguage] || TRANSLATIONS.en;
  if (dict && dict[key]) {
    return dict[key];
  }
  return TRANSLATIONS.en[key] || key;
}
